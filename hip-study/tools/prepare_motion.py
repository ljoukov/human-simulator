"""Prepare synchronized anatomical landmark clips from the named source recordings.

Usage: python prepare_motion.py --oa gait03.c3d --implant h1l_060511_1_47_mov.csv
       --implant h1l_060511_1_24_mov.csv --benchmarks hip-study/data/implants.json
       --predsim-clip predsim.json --output hip-study/data/motion.json
Requires numpy and c3d. Optional PredSim clips are generated by predsim_motion.py.
Omit --implant to prepare clips without OrthoLoad recordings.
"""

import argparse
import csv
import hashlib
import json
from pathlib import Path

import c3d
import numpy as np

PARTS = ("Shoulder", "Elbow", "Wrist", "Hand", "Hip", "Knee", "Ankle", "Heel", "Toe")
JOINTS = ["pelvis", "chest", "neck", "head"] + [
    side + part for side in ("left", "right") for part in PARTS
]
PHASE = np.linspace(0.0, 1.0, 101)
HIP_SOURCE = "Bertaux A. et al. Scientific Data 9, 399 (2022). CC BY 4.0."
ORTHO_SOURCE = ("Bergmann G. and Damm P. (eds.), Julius Wolff Institute, "
                "Berlin Institute of Health at Charité Universitätsmedizin Berlin (2008). "
                "OrthoLoad, {trial}. Retrieved 22 November 2026.")


def unit(vector):
    magnitude = np.linalg.norm(vector, axis=-1, keepdims=True)
    if np.any(magnitude < 1e-8):
        raise ValueError("A segment used to define an anatomical basis is degenerate")
    return vector / magnitude


def interpolate(values, times, targets):
    """Use only genuine samples either side of the target and reject tracking gaps."""
    valid = np.all(np.isfinite(values), axis=1)
    t, data = times[valid], values[valid]
    if len(t) < 2 or t[0] > targets[0] + 1e-7 or t[-1] < targets[-1] - 1e-7:
        raise ValueError("Requested phase extends outside measured landmarks")
    bracket = np.clip(np.searchsorted(t, targets), 1, len(t) - 1)
    if np.max(t[bracket] - t[bracket - 1]) > 0.08:
        raise ValueError("Landmark gap longer than 80 ms in selected phase")
    return np.column_stack([np.interp(targets, t, col) for col in data.T])


def make_frames(landmarks_mm, hip_angles, side, standing_forward=None):
    """Use a single, fixed frame for the entire clip to preserve relative pelvis rotation."""
    native = np.stack([landmarks_mm[name] for name in JOINTS], axis=1) / 1000.0
    pelvis = native[:, 0]
    # A robust walking direction in the horizontal plane, averaged across the recording.
    heading = np.polyfit(PHASE, pelvis, 1)[0] if standing_forward is None else standing_forward.copy()
    heading[2] = 0.0
    forward = unit(heading)
    vertical = np.array([0.0, 0.0, 1.0])
    right = np.cross(forward, vertical)
    basis = np.stack([forward, vertical, right], axis=1)
    world = native @ basis
    if np.any(world[:, JOINTS.index("rightHip"), 2] <= world[:, JOINTS.index("leftHip"), 2]):
        raise ValueError("Sagittal plane orientation does not agree with labelled left and right hips")
    distance = world[-1, 0, 0] - world[0, 0, 0] if standing_forward is None else 0.0
    world[:, :, 0] -= (world[0, 0, 0] + PHASE * distance)[:, None]
    world[:, :, 2] -= np.mean(world[:, 0, 2])
    selector = 0 if side == "left" else 1
    frames = []
    for i, p in enumerate(PHASE):
        angles = hip_angles[i]
        frames.append({
            "phase": round(float(p), 3),
            "points": world[i].round(5).tolist(),
            "hipFlexionDeg": round(float(angles[selector, 0]), 3),
            "hipAdductionDeg": round(float(angles[selector, 1]), 3),
            "hipsDeg": angles.round(3).tolist(),
        })
    return frames, float(distance)


def bertaux(path):
    digest = hashlib.sha256(path.read_bytes()).hexdigest()
    if digest != "3cbb12f2b060075be74b51858bc07967659b6000d615683437aa98609a904d39":
        raise ValueError("Expected the unmodified HOA001 preoperative gait03.c3d from the v2 archive")
    with path.open("rb") as stream:
        reader = c3d.Reader(stream)
        labels = [name.strip() for name in reader.point_labels]
        frame_times = (np.arange(reader.first_frame, reader.last_frame + 1) - 1) / reader.point_rate
        event_times = reader.get("EVENT:TIMES").float_array @ np.array([60.0, 1.0])
        labels_events = [s.strip() for s in reader.get("EVENT:LABELS").string_array]
        sides = [s.strip() for s in reader.get("EVENT:CONTEXTS").string_array]
        events = list(zip(event_times, labels_events, sides))
        strikes = [t for t, e, s in events if e == "Foot Strike" and s == "Right"]
        start, end = strikes[1:3]  # Interior stride avoids start/stop transitions.
        toe_off = next(t for t, e, s in events if e == "Foot Off" and s == "Right" and start < t < end)
        times = start + PHASE * (end - start)
        points = np.stack([row for _, row, _ in reader.read_frames()])
        rate = float(reader.point_rate)
    # Source C3D's fourth number is residual; negative marks a missing sample.
    points[points[:, :, 3] < 0, :3] = np.nan

    def get(name):
        return interpolate(points[:, labels.index(name), :3], frame_times, times)

    landmark = {
        "pelvis": get("PELO"), "chest": (get("STRN") + get("T10")) / 2,
        "neck": (get("CLAV") + get("C7")) / 2,
        "head": np.mean([get(label) for label in ("LFHD", "RFHD", "LBHD", "RBHD")], axis=0),
    }
    for side, prefix in (("left", "L"), ("right", "R")):
        # In this Vicon export the proximal endpoint of the femur is the HJC.
        # The midpoint of LFEP/RFEP agrees with PELO to within 0.001 mm.
        for part, suffix in zip(PARTS, ("CLO","HUO","RAO","FIN","FEP","FEO","TIO","HEE","TOE")):
            landmark[side + part] = get(prefix + suffix)
    midpoint_residual = np.max(np.linalg.norm((landmark["leftHip"] + landmark["rightHip"]) / 2 - landmark["pelvis"], axis=1))
    if midpoint_residual > 0.01:
        raise ValueError("Proximal femur endpoints inconsistent with Vicon pelvic origin")
    angles = np.stack([get("LHipAngles")[:, :2], get("RHipAngles")[:, :2]], axis=1)
    frames, distance = make_frames(landmark, angles, "right")
    return {
        "id": "bertaux-hoa001", "label": "Preoperative hip OA", "side": "right",
        "kind": "recorded", "phaseLabel": "Right gait cycle", "durationS": round(end-start, 5),
        "startS": round(start, 5), "endS": round(end, 5), "toeOffPhase": round((toe_off-start)/(end-start),5),
        "source": HIP_SOURCE, "sourceUrl": "https://doi.org/10.6084/m9.figshare.14420645.v2",
        "trial": "Patients/HOA001/M0/gait/gait03.c3d", "sourceRateHz": rate,
        "sourceSha256": digest,
        "clinicalMetadataUrl": "https://doi.org/10.6084/m9.figshare.13655975",
        "notes": "Participant HOA001, preoperative right hip OA (KL 4). Two successive recorded right foot strikes bound this stride. Shoulders, elbows, wrists, hips, knees and ankles use Vicon Plug-in Gait segment endpoints. Hands, heels and forefeet use surface markers. Head, neck and chest use marker midpoints. The signed hip angles come from the source Plug-in Gait output.",
        "progressionM": round(distance, 4), "frames": frames,
    }


def orthoload(path, trial):
    with path.open(encoding="utf-8-sig") as stream:
        header = [next(stream) for _ in range(16)]
        columns = [s.strip() for s in next(csv.reader([header[14]]))]
        values = np.loadtxt(stream, delimiter=",")
    digest = hashlib.sha256(path.read_bytes()).hexdigest()
    if trial["file"].lower() not in header[1].lower() or digest != trial["sourceSha256"]:
        raise ValueError("OrthoLoad filename or digest differs from the benchmark recording")
    # Companion CSV uses kN for plate forces, N for implant telemetry.
    bw_n = float(header[4].split(",")[1].strip().rstrip("N"))
    time = values[:, 0]
    fz = values[:, columns.index(f"Fz{trial['plate']}")]
    finite = np.isfinite(fz)
    loaded = np.interp(time, time[finite], fz[finite]) * 1000 / bw_n > .05
    # Take the source interval directly from the force benchmark. Some trials
    # contain two traverses whose source time coordinates differ.
    start, end = trial["startS"], trial["endS"]
    if np.mean(loaded[(time >= start+.02) & (time <= end-.02)]) < .97:
        raise ValueError("Selected contact incompatible with vertical ground reaction")
    sample_times = start + PHASE * (end-start)

    def get(label):
        i = columns.index(label)
        return interpolate(values[:, i:i+3], time, sample_times)

    anterior = (get("RASIS") + get("LASIS")) / 2
    posterior = (get("RPSIS") + get("LPSIS")) / 2
    across = get("RASIS") - get("LASIS")
    right = unit(across)
    up = unit(np.cross(right, anterior-posterior))
    forward = unit(np.cross(up, right))
    width = np.linalg.norm(across, axis=1, keepdims=True)
    depth = np.linalg.norm(anterior-posterior, axis=1, keepdims=True)
    hip_mid = anterior + (-0.24*depth-9.9)*forward + (-0.30*width-10.9)*up
    shoulder_mid = (get("RSHO") + get("LSHO")) / 2
    trunk_up = unit(shoulder_mid - get("L5"))
    shoulder_width = np.median(np.linalg.norm(get("RSHO") - get("LSHO"), axis=1))
    landmark = {"pelvis": hip_mid, "chest": (get("TH12") + shoulder_mid)/2, "neck": shoulder_mid,
                "head": shoulder_mid + .58*shoulder_width*trunk_up}
    bilateral = []
    for side, prefix, sign in (("left", "L", -1), ("right", "R", 1)):
        hip = hip_mid + sign * (.33*width + 7.3)*right
        knee = (get(prefix+"MCO") + get(prefix+"LCO")) / 2
        ankle = (get(prefix+"MMA") + get(prefix+"LMA")) / 2
        heel = get(prefix+"HEEL")
        toe = (get(prefix+"MET01") + get(prefix+"MET05")) / 2
        # Arms/head in this acquisition have no distal tracking. Complete them
        # at neutral rest attached to the observed shoulders for context only.
        shoulder = get(prefix+"SHO")
        elbow = shoulder + shoulder_width*(-.88*trunk_up + .10*sign*right)
        wrist = elbow + shoulder_width*(-.69*trunk_up + .20*forward)
        hand = wrist + shoulder_width*(-.32*trunk_up + .04*forward)
        for part, point in zip(PARTS, (shoulder,elbow,wrist,hand,hip,knee,ankle,heel,toe)):
            landmark[side+part] = point
        thigh = knee-hip
        anterior_thigh = np.sum(thigh*forward, axis=1)
        inferior_thigh = -np.sum(thigh*up, axis=1)
        medial_thigh = -sign*np.sum(thigh*right, axis=1)
        bilateral.append(np.rad2deg(np.stack([np.arctan2(anterior_thigh, inferior_thigh),
                                                np.arctan2(medial_thigh,inferior_thigh)],axis=1)))
    side = {"R":"right","L":"left"}[trial["side"]]
    standing = trial["activity"] == "stand"
    heading = np.mean(forward, axis=0) if standing else None
    frames, distance = make_frames(landmark, np.stack(bilateral,axis=1), side, heading)
    # Benchmark interpolates already-computed angles; the viewer reconstructs
    # centers from interpolated optical markers. Compare the independent paths.
    error = max(abs(a[key] - b[key]) for a, b in zip(frames, trial["frames"])
                for key in ("hipFlexionDeg", "hipAdductionDeg"))
    if error > 0.02 or len(frames) != len(trial["frames"]):
        raise ValueError(f"Pose and force benchmark kinematics diverged by {error:.3f} degrees")
    return {
        "id": f"{trial['subject'].lower()}-{trial['activity']}", "label": "Instrumented single-leg stand" if standing else "Instrumented hip walk", "trial": trial["id"],
        "kind": "recorded", "side": side, "durationS": round(end-start, 5),
        "source": ORTHO_SOURCE.format(trial=trial["id"]), "sourceUrl": "https://orthoload.com/hip-joint-force-and-motion-capture-data/",
        "termsUrl": "https://orthoload.com/infos/legal-information/",
        "sourceSha256": digest,
        "sourceRateHz": 120, "progressionM": round(distance,4),
        "phaseLabel": f"{side.capitalize()} single-leg stand" if standing else f"{side.capitalize()} instrumented stance", "startS": start, "endS": end,
        "notes": f"Derived articulated pose during {side}-foot plate contact. Hip centers use pelvis-only Harrington regression, ankles and knees use paired bony markers, and shoulder positions come from optical tracking. Head and arms below shoulders are illustrative reconstructions. Hip angles project the estimated thigh axis into pelvic planes. Source marker samples at 120 Hz are interleaved in the synchronized 960-Hz export.",
        "frames": frames,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--oa", type=Path, required=True)
    parser.add_argument("--implant", type=Path, action="append", default=[])
    parser.add_argument("--benchmarks", type=Path, default=Path(__file__).resolve().parents[1] / "data/implants.json")
    parser.add_argument("--predsim-clip", action="append", default=[], type=Path)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    clips = [bertaux(args.oa)]
    if args.implant:
        trials = {trial["file"].lower(): trial for trial in json.loads(args.benchmarks.read_text())["trials"]}
        clips.extend(orthoload(path, trials[path.name.lower()]) for path in args.implant)
    for path in args.predsim_clip:
        content = json.loads(path.read_text())
        clips.extend(content if isinstance(content, list) else [content])
    output = {
        "schemaVersion": 1, "jointNames": JOINTS, "axes": "+X forward, +Y up, +Z anatomical right", "units": "m",
        "phaseDefinition": "Fraction of each clip's declared source interval, sampled at equal time steps.",
        "hipsDegDefinition": "Left, right pairs of flexion and adduction angles in degrees. Positive indicates flexion/adduction.",
        "displayFrame": "Recorded landmarks retain lateral and vertical sway in a fixed lab frame. Linear forward progression is removed for in-place playback.",
        "clips": clips,
    }
    args.output.parent.mkdir(exist_ok=True, parents=True)
    args.output.write_text(json.dumps(output,separators=(",",":"),allow_nan=False)+"\n")
    for clip in clips:
        print(clip["id"], len(clip["frames"]), "frames,", clip["durationS"], "seconds")


if __name__ == "__main__":
    main()
